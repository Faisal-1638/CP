#include <bits/stdc++.h>
using namespace std;

int main() 
{
    char ch = 'A';

    cout << (int)ch;

    cout << char(97);

//Convert lowercase → uppercase
    char ch = 'b';

    ch = ch - 32;

    cout << ch;
    
//Convert uppercase → lowercase
    char ch = 'D';
    ch = ch + 32;

    cout << ch;
return 0;

}